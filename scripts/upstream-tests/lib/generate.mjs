// 从基线的编译产物机械地生成被测文件。原文件只读，生成物写到输出目录，不入库。
//
// 改写规则（每条都核对命中次数，与预期不符就报错退出，防止上游文本变了而改写悄悄失效）：
//   R1 相对 import（静态与动态）改成指向基线 dist 的绝对 file URL。
//   R2 `import test from "node:test"` 改成 runtime.mjs 的包装（按 manifest 跳过、记录是否碰到 sidecar）。
//   R3 loopbackConnection()（进程内 TS sidecar server）改成外部 sidecar 子进程；原函数改名保留。
//   R4 stdio 连接的 `command: process.execPath, args: [builtSidecarPath()]` 改成被测 sidecar 的命令。
//   R5 TCP 用例的 `spawn(process.execPath, [builtSidecarPath()], …)` 同上。
//   R6 createLocalGateway 的 stdio 部署环境追加被测 sidecar 的生产选择变量。
//   R7 `process.cwd()`（上游假定 cwd 是基线仓库根）改成隔离的根目录。
//   R8 （只用于 sidecar.spec）`new AgentLoopSidecarServer(` 改成 runtime 的 sidecarServer(：serve() 拉起外部 sidecar。
// 断言、用例名、用例体的其余部分逐字保留。
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { GROUPS } from './manifest.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const RUNTIME_URL = pathToFileURL(join(HERE, 'runtime.mjs')).href;

const RULES = {
  client: { R3: 1, R4: 2, R5: 0, R6: 0, R7: 3 },
  tcp: { R3: 0, R4: 0, R5: 2, R6: 0, R7: 1 },
  deployment: { R3: 0, R4: 0, R5: 0, R6: 1, R7: 0 },
  stdio: { R3: 0, R4: 0, R5: 0, R6: 0, R7: 0, R8: 20 },
};

function replaceCounted(text, pattern, replacement, expected, label) {
  let count = 0;
  const out = text.replace(pattern, (...args) => {
    count += 1;
    return typeof replacement === 'function' ? replacement(...args) : replacement;
  });
  if (expected !== undefined && count !== expected) {
    throw new Error(`${label}: expected ${expected} replacement(s), got ${count}`);
  }
  return { out, count };
}

export function generateGroup(baseline, group, outDir) {
  const spec = GROUPS[group];
  if (!spec) throw new Error(`unknown group ${group}`);
  const sourcePath = join(baseline, spec.source);
  const sourceDir = dirname(sourcePath);
  let text = readFileSync(sourcePath, 'utf8');
  const rules = RULES[group];
  const counts = {};

  // R1
  ({ out: text, count: counts.R1 } = replaceCounted(
    text,
    /((?:\bfrom|\bimport)\s*\(?\s*)"(\.\.?\/[^"]+)"/g,
    (_m, prefix, rel) => `${prefix}"${pathToFileURL(resolve(sourceDir, rel)).href}"`,
    undefined, `${group} R1`));
  if (counts.R1 === 0) throw new Error(`${group} R1: no relative imports found`);
  // R2
  ({ out: text, count: counts.R2 } = replaceCounted(
    text, /^import test from "node:test";$/m,
    `import test, * as __pdrs from "${RUNTIME_URL}";`, 1, `${group} R2`));
  // R3
  ({ out: text, count: counts.R3 } = replaceCounted(
    text, /^function loopbackConnection\(\) \{$/m,
    'function loopbackConnection() { return __pdrs.externalConnection(__upstream_loopbackConnection); }\n'
      + 'function __upstream_loopbackConnection() {',
    rules.R3, `${group} R3`));
  // R4
  ({ out: text, count: counts.R4 } = replaceCounted(
    text, /command: process\.execPath,(\s*)args: \[builtSidecarPath\(\)\],/g,
    (_m, ws) => `command: __pdrs.sidecarCommand(),${ws}args: __pdrs.sidecarArgs(),`,
    rules.R4, `${group} R4`));
  // R5
  ({ out: text, count: counts.R5 } = replaceCounted(
    text, /spawn\(process\.execPath, \[builtSidecarPath\(\)\], \{/g,
    'spawn(__pdrs.sidecarCommand(), __pdrs.sidecarArgs(), {',
    rules.R5, `${group} R5`));
  // R6
  ({ out: text, count: counts.R6 } = replaceCounted(
    text, /env: \{ PILOTDECK_AGENT_LOOP_TRANSPORT: "stdio" \},/g,
    'env: { PILOTDECK_AGENT_LOOP_TRANSPORT: "stdio", ...__pdrs.stdioDeploymentEnv() },',
    rules.R6, `${group} R6`));
  // R7
  ({ out: text, count: counts.R7 } = replaceCounted(
    text, /process\.cwd\(\)/g, '__pdrs.cwdRoot()', rules.R7, `${group} R7`));

  // R8
  if (rules.R8 !== undefined) {
    ({ out: text, count: counts.R8 } = replaceCounted(
      text, /new AgentLoopSidecarServer\(/g, '__pdrs.sidecarServer(', rules.R8, `${group} R8`));
  }

  const header = `// GENERATED by scripts/upstream-tests/lib/generate.mjs from ${spec.source} — do not edit.\n`;
  mkdirSync(outDir, { recursive: true });
  const outPath = join(outDir, `${group}.spec.mjs`);
  writeFileSync(outPath, header + text);
  const upstreamTests = countTests(readFileSync(sourcePath, 'utf8'));
  return { group, outPath, counts, upstreamTests };
}

/** 上游文件里 test(...) 的个数；for 循环里的按循环展开数计（tcp 的 crashStage 有两个取值）。 */
function countTests(text) {
  const direct = (text.match(/^\s*test\(/gm) ?? []).length;
  const loops = [...text.matchAll(/^for \(const \w+ of \[([^\]]*)\]\) \{\n\s*test\(/gm)];
  let extra = 0;
  for (const loop of loops) extra += loop[1].split(',').length - 1;
  return direct + extra;
}
