import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const [file,scene] = process.argv.slice(2); assert.ok(file && scene, 'provide capture and explicit scenario');
const a=JSON.parse(fs.readFileSync(file,'utf8'));
assert.equal(a.scenario,'agent03-sdk-fork-lifecycle-probe');
const sha=createHash('sha256').update(fs.readFileSync(scene)).digest('hex');
assert.equal(sha,'9459860c1d83f7fdb71f37cb56a20ee0ae38655cf265b9294274fb61610f0e80');
assert.equal(a.evidence?.scenario?.sha256,sha,'capture bound to scenario bytes');
assert.equal(a.evidence?.inputs?.ts?.commit,'cc7c4e653b15c8b2cec7bcf2d15d41d69396ae85');
assert.deepEqual((a.failures??[]).filter(x=>!x.expected),[]);
assert.ok(a.provider?.['memory-gate']?.length>0,'actual memory gate request');
const parent=a.provider?.parent?.[0]?.body, child=a.provider?.['child-alpha']?.[0]?.body;
assert.ok(parent && child,'actual parent and child model requests');
const parentSystem=(parent.messages??[]).filter(x=>x.role==='system').map(x=>JSON.stringify(x.content)).join('\n');
assert.match(parentSystem,/AG03-MEMORY-POSITIVE-IDENTITY/,'parent actually received controlled retrieved memory');
assert.doesNotMatch(JSON.stringify(child),/AG03-MEMORY-POSITIVE-IDENTITY/,'memory-disabled child must not receive marker');
const log=a.tree?.['/home/.pilotdeck/agent03-mcp-log.jsonl']?.jsonl;
assert.ok(Array.isArray(log));
const get=name=>{const x=log.filter(e=>e.event===name);assert.equal(x.length,1,`one ${name}`);return x[0]};
for(const n of ['start','initialize','tools/list','tools/call'])get(n);
const held=get('close-held'),released=get('close-released'),exit=get('exit');
assert.ok(Number.isSafeInteger(held.atMs)&&released.atMs-held.atMs>=900&&exit.atMs>=released.atMs,'MCP close barrier held at least 900 ms');
const paths=Object.keys(a.tree??{}).filter(p=>p.endsWith('/chats/agent03-parent.jsonl'));assert.equal(paths.length,1);
const rows=a.tree[paths[0]].jsonl;
const completions=rows.filter(e=>e.type==='subagent_completed'&&e.subagentType==='worker');assert.equal(completions.length,1);
const done=completions[0], doneTime=Date.parse(done.createdAt);assert.ok(Number.isFinite(doneTime)&&doneTime>exit.atMs,'child completion persisted strictly after MCP exit callback');
const result=rows.find(e=>e.type==='tool_result_message'&&e.sequence>done.sequence&&JSON.stringify(e).includes('ag03-agent'));assert.ok(result,'parent receives agent result after child completion');
console.log(JSON.stringify({passed:true,marker:'AG03-MEMORY-POSITIVE-IDENTITY',heldMs:released.atMs-held.atMs,exitAt:exit.atMs,childCompletedAt:doneTime,childSequence:done.sequence,resultSequence:result.sequence}));
