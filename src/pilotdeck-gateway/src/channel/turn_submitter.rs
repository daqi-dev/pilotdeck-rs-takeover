//! Production A7 inbound port: the channel hands a turn to the same
//! `TurnSubmitter` the WS host owns. No session owner, admission or projection
//! state is created here.
use super::protocol::*;
use crate::{
    metadata::object,
    runtime::turn::submit::{TurnSubmission, TurnSubmitter},
};
use pilotdeck_protocol::{JsString, JsValue};
use std::sync::Arc;

pub struct SubmitterTurnGateway {
    submitter: Arc<TurnSubmitter>,
    owned: bool,
}

impl SubmitterTurnGateway {
    /// The submitter is shared; the channel identity travels on each request
    /// (`TurnRequest.channel_key`), like the TS adapters' `submitTurn`
    /// `channelKey` field — the gateway never stamps one of its own.
    pub fn new(submitter: Arc<TurnSubmitter>) -> Self {
        Self {
            submitter,
            owned: false,
        }
    }
    pub fn new_owned(submitter: Arc<TurnSubmitter>) -> Self {
        Self {
            submitter,
            owned: true,
        }
    }
}

impl TurnGateway for SubmitterTurnGateway {
    fn submit(
        &self,
        request: TurnRequest,
    ) -> BoxFuture<Result<Box<dyn TurnEventStream>, ChannelError>> {
        // The basic adapters pass these three fields (the api-server's
        // `channelKey: "api_server"`, ApiServerChannel.ts:319/:376); absent
        // runId is generated by the acceptor, as in InProcessGateway.submitTurn.
        // #2301 fix-r1: the requester's key, never a construction-time one —
        // the shared assembly gateway used to overwrite it with the first
        // consumer's identity, so an apiServer turn entered A7 as `feishu`.
        let owned = self.owned;
        let mut input = object([
            ("sessionKey", JsValue::String(request.session_key)),
            (
                "channelKey",
                JsValue::String(request.channel_key.as_js().clone()),
            ),
            ("message", JsValue::String(request.message)),
        ]);
        if let JsValue::Object(fields) = &mut input {
            if let Some(attachments) = request.attachments {
                fields.insert("attachments".into(), JsValue::Array(attachments));
            }
            if let Some(enabled) = request.allow_plan_mode_tools {
                fields.insert("allowPlanModeTools".into(), JsValue::Bool(enabled));
            }
            if let Some(mode) = request.mode {
                fields.insert("mode".into(), JsValue::String(mode));
            }
            if let Some(mode) = request.base_permission_mode {
                fields.insert("basePermissionMode".into(), JsValue::String(mode));
            }
            if let Some(timeout) = request.timeout_ms {
                fields.insert("timeoutMs".into(), JsValue::Number(timeout));
            }
            if let Some(messages) = request.synthetic_messages {
                fields.insert("syntheticMessages".into(), JsValue::Array(messages));
            }
            if let Some(project) = request.project_key {
                fields.insert("projectKey".into(), JsValue::String(project));
            }
        }
        if !owned {
            // Preserve the legacy call boundary: the submission starts before
            // the returned future is polled, as it did before owned streams.
            let submission = self.submitter.submit(input);
            return Box::pin(async move {
                Ok(Box::new(SubmissionStream(submission)) as Box<dyn TurnEventStream>)
            });
        }
        let submitter = self.submitter.clone();
        // Owned creation and transfer occur in one poll. An unpolled/dropped
        // submit future cannot leave a hidden channel-owned turn.
        Box::pin(async move {
            Ok(Box::new(SubmissionStream(submitter.submit_owned(input)))
                as Box<dyn TurnEventStream>)
        })
    }
}

struct SubmissionStream(TurnSubmission);

impl TurnEventStream for SubmissionStream {
    fn cancel_and_drain(
        &mut self,
        reason: JsString,
    ) -> std::pin::Pin<Box<dyn std::future::Future<Output = Result<(), ChannelError>> + Send + '_>>
    {
        Box::pin(async move {
            self.0
                .cancel_and_drain(reason)
                .await
                .map_err(|error| ChannelError::Error(error.message))
        })
    }

    fn next(
        &mut self,
    ) -> std::pin::Pin<
        Box<dyn std::future::Future<Output = Result<Option<JsValue>, ChannelError>> + Send + '_>,
    > {
        Box::pin(async move {
            self.0
                .next()
                .await
                .map_err(|error| ChannelError::Error(error.message))
        })
    }
}
